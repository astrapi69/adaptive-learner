class GitHub:
    """Minimal REST reader with pagination; every failure raises FetchError."""

    def __init__(self, token: str | None) -> None:
        self.token = token

    def _request(self, url: str) -> tuple[Any, str]:
        headers = {
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "adaptive-learner-status-board",
        }
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        try:
            with urllib.request.urlopen(
                urllib.request.Request(url, headers=headers), timeout=60
            ) as resp:
                return json.loads(resp.read().decode("utf-8")), resp.headers.get("Link", "")
        except (urllib.error.URLError, json.JSONDecodeError, TimeoutError) as exc:
            raise FetchError(f"GET {url}: {exc}") from exc

    def get(self, path: str) -> Any:
        url = path if path.startswith("https://") else f"https://api.github.com/{path}"
        return self._request(url)[0]

    def get_optional(self, path: str) -> Any | None:
        """Like :meth:`get`, but ``None`` for HTTP 404; every other failure raises."""
        try:
            return self.get(path)
        except FetchError as exc:
            cause = exc.__cause__
            if isinstance(cause, urllib.error.HTTPError) and cause.code == 404:
                return None
            raise

    def get_all(self, path: str) -> list[Any]:
        url: str | None = f"https://api.github.com/{path}"
        items: list[Any] = []
        while url:
            page, link = self._request(url)
            items.extend(page)
            match = re.search(r'<([^>]+)>;\s*rel="next"', link)
            url = match.group(1) if match else None
        return items


def _repo_of(url: str, owner: str) -> str:
    parts = url.rstrip("/").split("/")
    return parts[-1] if parts[-2] == owner else f"{parts[-2]}/{parts[-1]}"


def _attach_commit_messages(gh: GitHub, events: list[dict[str, Any]]) -> None:
    """Give each ``referenced`` event its commit message (#3902).

    The timeline carries only ``commit_id`` and ``commit_url``, so this costs
    one request per such event. A commit that no longer exists (404) stays
    without a message and is not movement; any other failure raises FetchError.
    """
    for event in events:
        if event.get("event") != "referenced" or not event.get("commit_url"):
            continue
        commit = gh.get_optional(event["commit_url"])
        if commit is not None:
            event["commit_message"] = (commit.get("commit") or {}).get("message") or ""


def _fetch_issues(gh: GitHub, owner: str, repo: str) -> tuple[dict[str, Issue], dict[str, dict]]:
    issues: dict[str, Issue] = {}
    raw: dict[str, dict] = {}
    for item in gh.get_all(f"repos/{owner}/{repo}/issues?state=open&per_page=100"):
        if "pull_request" in item or STATUS_REPORT_MARKER in (item.get("body") or ""):
            continue
        number = item["number"]
        events = gh.get_all(f"repos/{owner}/{repo}/issues/{number}/timeline?per_page=100")
        _attach_commit_messages(gh, events)
        deps = gh.get_all(
            f"repos/{owner}/{repo}/issues/{number}/dependencies/blocked_by?per_page=100"
        )
        api_blocked = tuple(
            issue_key(_repo_of(dep["repository_url"], owner), dep["number"]) for dep in deps
        )
        issue = Issue(
            repo=repo,
            number=number,
            title=item["title"],
            url=item["html_url"],
            labels=tuple(label["name"] for label in item.get("labels", [])),
            last_movement=last_movement(events, item["created_at"], (owner, repo, number)),
            api_blocked_by=api_blocked,
            open_pr_refs=open_pr_refs(events, (owner, repo, number)),
        )
        issues[issue.key] = issue
        raw[issue.key] = {"item": item, "events": events}
    return issues, raw


def _latest_semver_tag(gh: GitHub, owner: str, repo: str) -> str | None:
    tags = [t["name"] for t in gh.get_all(f"repos/{owner}/{repo}/tags?per_page=100")]
    versions = [
        (tuple(int(p) for p in m.groups()), t) for t in tags if (m := SEMVER_TAG_RE.match(t))
    ]
    return max(versions)[1] if versions else None


def _npm_latest(package: str) -> str:
    url = f"https://registry.npmjs.org/{package}/latest"
    try:
        with urllib.request.urlopen(url, timeout=60) as resp:
            return str(json.loads(resp.read().decode("utf-8"))["version"])
    except (urllib.error.URLError, json.JSONDecodeError, KeyError, TimeoutError) as exc:
        raise FetchError(f"GET {url}: {exc}") from exc


def _now_lines(gh: GitHub, owner: str, repos: tuple[RepoConfig, ...]) -> tuple[str, ...]:
    lines = []
    for repo in repos:
        if repo.release == "github":
            rel = gh.get(f"repos/{owner}/{repo.name}/releases/latest")
            lines.append(
                f"{repo.name}: {rel['tag_name']} (GitHub Release, {rel['published_at'][:10]})"
            )
        elif repo.release == "tag":
            line = f"{repo.name}: tag {_latest_semver_tag(gh, owner, repo.name) or 'none'}"
            if repo.npm:
                line += f", npm {repo.npm} {_npm_latest(repo.npm)}"
            lines.append(line)
    counts = []
    for repo in repos:
        prs = gh.get_all(f"repos/{owner}/{repo.name}/pulls?state=open&per_page=100")
        prs = [
            p for p in prs if REGENERATION_LABEL not in {lbl["name"] for lbl in p.get("labels", [])}
        ]
        if prs:
            counts.append(f"{repo.name} {len(prs)}")
    total = sum(int(c.rsplit(" ", 1)[1]) for c in counts)
    lines.append(f"Open pull requests: {total}" + (f" ({', '.join(counts)})" if counts else ""))
    return tuple(lines)


def _recent(gh: GitHub, owner: str, repos: tuple[RepoConfig, ...]) -> tuple[str, ...]:
    happened: list[tuple[str, str]] = []
    for repo in repos:
        for pr in gh.get(
            f"repos/{owner}/{repo.name}/pulls?state=closed&sort=updated&direction=desc&per_page=15"
        ):
            labels = {lbl["name"] for lbl in pr.get("labels", [])}
            if pr.get("merged_at") and REGENERATION_LABEL not in labels:
                happened.append(
                    (
                        pr["merged_at"],
                        f"{pr['merged_at'][:10]} {repo.name}#{pr['number']} merged: {pr['title']}",
                    )
                )
        for item in gh.get(
            f"repos/{owner}/{repo.name}/issues?state=closed&sort=updated&direction=desc&per_page=15"
        ):
            if "pull_request" in item or not item.get("closed_at"):
                continue
            if STATUS_REPORT_MARKER in (item.get("body") or ""):
                continue
            reason = item.get("state_reason") or "completed"
            happened.append(
                (
                    item["closed_at"],
                    f"{item['closed_at'][:10]} {repo.name}#{item['number']} "
                    f"closed ({reason}): {item['title']}",
                )
            )
    happened.sort(reverse=True)
    return tuple(line for _, line in happened[:RECENT_LIMIT])


def _closed_keys(gh: GitHub, owner: str, keys: set[str], open_keys: set[str]) -> frozenset[str]:
    closed = set()
    for key in sorted(keys - open_keys):
        repo, number = key.split("#")
        if "/" in repo:
            continue
        try:
            item = gh.get(f"repos/{owner}/{repo}/issues/{number}")
        except FetchError:
            continue
        if item.get("state") == "closed" and "pull_request" not in item:
            closed.add(key)
    return frozenset(closed)


def _ecosystem(gh: GitHub, owner: str, pattern: str) -> tuple[str, ...]:
    regex = re.compile(pattern)
    repos = gh.get_all(f"users/{owner}/repos?per_page=100&type=owner")
    return tuple(
        sorted(r["name"] for r in repos if regex.search(r["name"]) and not r.get("archived"))
    )


def fetch_snapshot(
    root: Path, entries: dict[str, Entry], *, with_ecosystem: bool
) -> tuple[Snapshot, dict]:
    """Read everything one run needs from GitHub (and npm)."""
    owner, pattern, repos = parse_repos(
        yaml.safe_load((root / "status/repos.yaml").read_text("utf-8"))
    )
    gh = GitHub(os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN"))
    issues: dict[str, Issue] = {}
    raw: dict[str, dict] = {}
    for repo in repos:
        repo_issues, repo_raw = _fetch_issues(gh, owner, repo.name)
        issues.update(repo_issues)
        raw.update(repo_raw)
    referenced = set(entries) | {t for e in entries.values() for t in e.blocked_by}
    referenced |= {t for i in issues.values() for t in i.api_blocked_by}
    snap = Snapshot(
        owner=owner,
        repos=repos,
        issues=issues,
        closed_keys=_closed_keys(gh, owner, referenced, set(issues)),
        now_lines=_now_lines(gh, owner, repos),
        recent=_recent(gh, owner, repos),
        ecosystem_repos=_ecosystem(gh, owner, pattern) if with_ecosystem and pattern else (),
        generated_at=datetime.now(UTC).replace(second=0, microsecond=0),
    )
    return snap, raw


# --- CLI ------------------------------------------------------------------------------


def _read(path: Path) -> str:
    return path.read_text("utf-8") if path.exists() else ""


def _dump_unclassified(path: Path, snap: Snapshot, entries: dict[str, Entry], raw: dict) -> None:
    dump = []
    for key in snap.issues:
        if key in entries:
            continue
        item, events = raw[key]["item"], raw[key]["events"]
        comments = [e for e in events if e.get("event") == "commented"][-3:]
        dump.append(
            {
                "key": key,
                "url": item["html_url"],
                "title": item["title"],
                "labels": [lbl["name"] for lbl in item.get("labels", [])],
                "body": item.get("body"),
                "last_comments": [
                    {"url": c.get("html_url"), "at": c.get("created_at"), "body": c.get("body")}
                    for c in comments
                ],
            }
        )
    path.write_text(json.dumps(dump, indent=1, ensure_ascii=False) + "\n", "utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("mode", choices=("render", "check"))
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument(
        "--dump-unclassified", type=Path, help="check: write open issues without an entry as JSON"
    )
    args = parser.parse_args(argv)
    root = args.root
    try:
        entries = parse_waits(yaml.safe_load(_read(root / "status/waits.yaml")))
    except (WaitsError, yaml.YAMLError) as exc:
        print(f"status/waits.yaml: {exc}", file=sys.stderr)
        return EXIT_FINDINGS
    try:
        snap, raw = fetch_snapshot(root, entries, with_ecosystem=args.mode == "check")
    except (FetchError, WaitsError, OSError) as exc:
        print(f"could not check: {exc}", file=sys.stderr)
        return EXIT_CANNOT_CHECK
    plan_path = root / "status/plan.md"
    plan = _read(plan_path) or None
    print(
        f"read {len(snap.issues)} open issues in {len(snap.repos)} repositories, "
        f"{len(entries)} entries in status/waits.yaml"
    )
    if args.mode == "render":
        missing = [key for key in snap.issues if key not in entries]
        if missing:
            print(
                "open issues without an entry in status/waits.yaml: " + ", ".join(missing),
                file=sys.stderr,
            )
            return EXIT_FINDINGS
        rows = build_rows(snap, entries)
        (root / "BOARD.md").write_text(render_board(snap, rows), "utf-8")
        (root / "STATUS.md").write_text(render_status(snap, rows, plan), "utf-8")
        print("wrote BOARD.md and STATUS.md")
        return EXIT_OK
    if args.dump_unclassified:
        _dump_unclassified(args.dump_unclassified, snap, entries, raw)
    findings = check(snap, entries, _read(root / "BOARD.md"), _read(root / "STATUS.md"), plan)
    for finding in findings:
        print(f"FAIL {finding}")
    if findings:
        print(f"{len(findings)} findings")
        return EXIT_FINDINGS
    print("status files and status/waits.yaml match GitHub")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
