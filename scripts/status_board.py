#!/usr/bin/env python3
"""Generate and check the ecosystem STATUS.md and BOARD.md (#3889).

Open work is spread over the repositories listed in ``status/repos.yaml``.
Two files in the repository root give one view of it, and both are
generated, never edited by hand:

``BOARD.md``   every open issue, grouped by what it waits for
``STATUS.md``  now, waiting for the owner, plan, recently happened, where
               things are

What an issue waits for is a judgement, so it lives in ``status/waits.yaml``
with a link to the evidence and the date it was checked. Everything else is
read from GitHub: the level (the ``P0``..``P5`` label), the last movement
(the newest comment, commit or pull request that works on the issue, from
the timeline API, never ``updated_at``: a label change is not movement, and
neither is a mention in a PR or a commit, #3898, #3902), GitHub's own
``dependencies/blocked_by``, and
the open pull requests that work on an issue. ``Blocks`` is computed as the inverse of every ``blocked_by``.

``check`` fails (exit 1) when the files or the classification no longer
match GitHub: an open issue without an entry, an entry for a closed or
unknown issue, an issue that moved after its entry was checked, a
``blocked_by`` on a closed or unknown issue, a GitHub ``blocked_by`` that
the entry does not say, a file older than the newest issue movement or
different from a fresh render, an ecosystem repository that is not listed.
It exits 2 when it cannot check at all (an API read fails, no repository
configured): "could not check" is never green (#2083).

Usage::

    python3 scripts/status_board.py render
    python3 scripts/status_board.py check [--dump-unclassified out.json]

``GITHUB_TOKEN`` (or ``GH_TOKEN``) is sent when set; public repositories
need nothing more.
"""

