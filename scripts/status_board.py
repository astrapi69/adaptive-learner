import yaml

STATUS_REPORT_MARKER = "<!-- status-board-report (#3889) -->"
REGENERATION_LABEL = "status-board"
WAITS_VALUES = ("decision", "external", "issue", "nothing")
LEVELS = ("P0", "P1", "P2", "P3", "P4", "P5")
MOVEMENT_EVENTS = frozenset({"commented", "referenced", "cross-referenced", "committed"})
STALE_AFTER = timedelta(days=14)
MAX_IN_PROGRESS = 5
MAX_NOW_LINES = 3
RECENT_LIMIT = 5

KEY_RE = re.compile(r"^[A-Za-z0-9._-]+#\d+$")
GENERATED_RE = re.compile(r"^(> )?Generated by `make status` at ")
STATE_RE = re.compile(r"Issue state as of (\d{4}-\d{2}-\d{2} \d{2}:\d{2}) UTC")
SEMVER_TAG_RE = re.compile(r"^v?(\d+)\.(\d+)\.(\d+)$")
# #3898: a PR works on an issue when a closing keyword or "Refs" names it; the
# references may form a list ("Refs #4, #5", "Refs #4 and #5").
_ISSUE_REF = r"(?:https://github\.com/[\w.-]+/[\w.-]+/issues/\d+|(?:[\w.-]+/[\w.-]+)?#\d+)"
WORK_REF_RE = re.compile(
    rf"\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?|refs?)\b:?\s+"
    rf"(?P<refs>{_ISSUE_REF}(?:\s*(?:,|\band\b)\s*{_ISSUE_REF})*)",
    re.IGNORECASE,
)
ISSUE_REF_RE = re.compile(
    r"https://github\.com/(?P<url_repo>[\w.-]+/[\w.-]+)/issues/(?P<url_number>\d+)"
    r"|(?P<repo>[\w.-]+/[\w.-]+)?#(?P<number>\d+)"
)

IssueRef = tuple[str, str, int]
"""An issue as (owner, repository, number)."""

EXIT_OK, EXIT_FINDINGS, EXIT_CANNOT_CHECK = 0, 1, 2


class WaitsError(ValueError):
    """A configuration file (waits.yaml or repos.yaml) is malformed."""


class FetchError(RuntimeError):
    """A GitHub or npm read failed; the run proves nothing."""


@dataclass(frozen=True)
class RepoConfig:
    """One repository of the ecosystem, as listed in ``status/repos.yaml``."""

    name: str
    role: str
    release: str = "none"
    npm: str | None = None


@dataclass(frozen=True)
class Issue:
    """The GitHub side of one open issue."""

    repo: str
    number: int
    title: str
    url: str
    labels: tuple[str, ...]
    last_movement: datetime
    api_blocked_by: tuple[str, ...] = ()
    open_pr_refs: tuple[str, ...] = ()

    @property
    def key(self) -> str:
        return issue_key(self.repo, self.number)


@dataclass(frozen=True)
class Entry:
    """The judged side of one open issue, from ``status/waits.yaml``."""

    key: str
    summary: str
    waits: str
    detail: str
    evidence: str
    checked: date
    blocked_by: tuple[str, ...] = ()
    needed_by: str | None = None


@dataclass(frozen=True)
class Snapshot:
    """Everything read from GitHub for one run."""

    owner: str
    repos: tuple[RepoConfig, ...]
    issues: dict[str, Issue]
    closed_keys: frozenset[str]
    now_lines: tuple[str, ...]
    recent: tuple[str, ...]
    ecosystem_repos: tuple[str, ...]
    generated_at: datetime


@dataclass
class Row:
    """An open issue joined with its entry."""

    issue: Issue
    entry: Entry
    blocked_by: tuple[str, ...]
    blocks: tuple[str, ...] = field(default=())

    @property
    def key(self) -> str:
        return self.issue.key

    @property
    def level(self) -> str:
        return level_of(self.issue.labels)


# --- small helpers -------------------------------------------------------------


def issue_key(repo: str, number: int) -> str:
    """Return the stable id ``repo#N`` used everywhere in these files."""
    return f"{repo}#{number}"


def level_of(labels: tuple[str, ...] | list[str]) -> str:
    """Return the highest ``P0``..``P5`` label, or ``none``."""
    present = [lvl for lvl in LEVELS if lvl in labels]
    return present[0] if present else "none"


def _parse_ts(value: str) -> datetime:
    return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(UTC)


def _fmt_ts(value: datetime) -> str:
    return value.astimezone(UTC).strftime("%Y-%m-%d %H:%M")


def _clean(text: str) -> str:
    """Make a value safe for a one-line table cell or list item."""
    text = text.replace("—", "-").replace("–", "-")
    return " ".join(text.split()).replace("|", "/")


def _is_board_own(event: dict[str, Any]) -> bool:
    """True for a reference made by the board itself.

    A PR labelled ``status-board`` lists every issue it classifies, and the
    nightly report issue names the ones it flags; GitHub records each such
    link as a cross-reference. Counted as movement, one regeneration PR
    would make every issue look fresh and empty the Stale block.
    """
    source = _source(event)
    labels = {label.get("name") for label in source.get("labels") or []}
    return REGENERATION_LABEL in labels or STATUS_REPORT_MARKER in (source.get("body") or "")


def _source(event: dict[str, Any]) -> dict[str, Any]:
    """The issue or pull request a cross-reference comes from (empty if none)."""
    return (event.get("source") or {}).get("issue") or {}


def works_on(source: dict[str, Any], target: IssueRef) -> bool:
    """Whether ``source`` is a pull request that works on ``target`` (#3898).

    It does when a closing keyword (close, fix, resolve and their forms) or
    ``Refs`` in its title or body names the issue. A short ``#N`` means the
    PR's own repository; ``owner/repo#N`` and the full issue URL name another
    one. A mention in the prose, and any mention from an issue, is not work.
    """
    if "pull_request" not in source:
        return False
    own = (source.get("repository") or {}).get("full_name") or ""
    text = f"{source.get('title') or ''}\n{source.get('body') or ''}"
    return names_as_work(text, own, target)


def names_as_work(text: str, own_repo: str, target: IssueRef) -> bool:
    """Whether a closing keyword or ``Refs`` in ``text`` names ``target``.

    A short ``#N`` means ``own_repo``; ``owner/repo#N`` and the full issue URL
    name another one. The shared test of :func:`works_on` and
    :func:`commit_works_on`.
    """
    wanted = (f"{target[0]}/{target[1]}".lower(), target[2])
    for match in WORK_REF_RE.finditer(text):
        for ref in ISSUE_REF_RE.finditer(match.group("refs")):
            if ref.group("url_number"):
                named = (ref.group("url_repo").lower(), int(ref.group("url_number")))
            else:
                named = ((ref.group("repo") or own_repo).lower(), int(ref.group("number")))
            if named == wanted:
                return True
    return False


def commit_works_on(event: dict[str, Any], target: IssueRef) -> bool:
    """Whether a ``referenced`` event's commit works on ``target`` (#3902).

    The same rule as for pull requests: the commit message names the issue
    with a closing keyword or ``Refs``. A mention in its prose is not work, nor
    is a commit whose message could not be fetched (``commit_message`` is
    attached by :func:`_attach_commit_messages`).
    """
    message = event.get("commit_message")
    if not message:
        return False
    return names_as_work(message, _commit_repo(event.get("commit_url") or ""), target)


def _commit_repo(commit_url: str) -> str:
    """``owner/repo`` of an API commit URL (``.../repos/owner/repo/commits/sha``)."""
    parts = commit_url.split("/repos/", 1)[-1].split("/")
    return f"{parts[0]}/{parts[1]}" if len(parts) >= 2 else ""


def last_movement(events: list[dict[str, Any]], created_at: str, target: IssueRef) -> datetime:
    """Return the newest comment, commit or working PR; the creation time if none.

    Label, title and assignment changes are not movement, which is why
    ``updated_at`` is never used; nor are the board's own references. A
    cross-reference counts only from a pull request that works on the issue
    (:func:`works_on`, #3898), a commit reference only from a commit whose
    message does (:func:`commit_works_on`, #3902): a mention from an issue, in
    a PR's prose or in a commit's prose moves nothing.
    """
    stamps = [created_at]
    for event in events:
        kind = event.get("event")
        if kind not in MOVEMENT_EVENTS or _is_board_own(event):
            continue
        if kind == "cross-referenced" and not works_on(_source(event), target):
            continue
        if kind == "referenced" and not commit_works_on(event, target):
            continue
        if kind == "committed":
            stamp = (event.get("committer") or {}).get("date") or (event.get("author") or {}).get(
                "date"
            )
        else:
            stamp = event.get("created_at")
        if stamp:
            stamps.append(stamp)
    return max(_parse_ts(s) for s in stamps)


def open_pr_refs(events: list[dict[str, Any]], target: IssueRef) -> tuple[str, ...]:
    """Return the open pull requests that work on the issue (:func:`works_on`)."""
    refs: list[str] = []
    for event in events:
        if event.get("event") != "cross-referenced" or _is_board_own(event):
            continue
        source = _source(event)
        if works_on(source, target) and source.get("state") == "open":
            url = source.get("html_url", "")
            if url and url not in refs:
                refs.append(url)
    return tuple(refs)


# --- configuration -----------------------------------------------------------


def parse_repos(raw: dict[str, Any]) -> tuple[str, str, tuple[RepoConfig, ...]]:
    """Parse ``status/repos.yaml`` into owner, ecosystem pattern and repositories."""
    owner = raw.get("owner")
    repos = raw.get("repos") or []
    if not owner or not repos:
        raise WaitsError("status/repos.yaml needs an owner and a non-empty repos list")
    configs = []
    for item in repos:
        if not item.get("name") or not item.get("role"):
            raise WaitsError(f"status/repos.yaml: every repository needs name and role: {item}")
        release = item.get("release", "none")
        if release not in ("github", "tag", "none"):
            raise WaitsError(
                f"status/repos.yaml: {item['name']}: release must be github, tag or none"
            )
        configs.append(RepoConfig(item["name"], item["role"], release, item.get("npm")))
    return owner, raw.get("ecosystem_pattern", ""), tuple(configs)


def _require_text(key: str, item: dict[str, Any], name: str) -> str:
    value = item.get(name)
    if not isinstance(value, str) or not value.strip():
        raise WaitsError(f"{key}: field {name} must be a non-empty string")
    return value.strip()


def parse_waits(raw: dict[str, Any] | None) -> dict[str, Entry]:
    """Parse and validate ``status/waits.yaml``."""
    entries: dict[str, Entry] = {}
    for key, item in ((raw or {}).get("issues") or {}).items():
        if not KEY_RE.match(str(key)):
            raise WaitsError(f"{key}: key must be repo#N")
        if not isinstance(item, dict):
            raise WaitsError(f"{key}: entry must be a mapping")
        waits = item.get("waits")
        if waits not in WAITS_VALUES:
            raise WaitsError(f"{key}: waits must be one of {', '.join(WAITS_VALUES)}")
        evidence = _require_text(key, item, "evidence")
        if not evidence.startswith("https://"):
            raise WaitsError(f"{key}: evidence must be a link")
        try:
            checked = date.fromisoformat(str(item.get("checked")))
        except ValueError as exc:
            raise WaitsError(f"{key}: checked must be a date (YYYY-MM-DD)") from exc
        blocked_by = tuple(str(b) for b in item.get("blocked_by") or ())
        if waits == "issue" and not blocked_by:
            raise WaitsError(f"{key}: waits issue needs blocked_by")
        if waits != "issue" and blocked_by:
            raise WaitsError(f"{key}: blocked_by is only allowed with waits issue")
        for target in blocked_by:
            if not KEY_RE.match(target):
                raise WaitsError(f"{key}: blocked_by entry {target} must be repo#N")
        needed_by = item.get("needed_by")
        entries[str(key)] = Entry(
            key=str(key),
            summary=_require_text(key, item, "summary"),
            waits=waits,
            detail=_require_text(key, item, "detail"),
            evidence=evidence,
            checked=checked,
            blocked_by=blocked_by,
            needed_by=str(needed_by) if needed_by else None,
        )
    return entries


# --- joining ------------------------------------------------------------------


def _sort_key(row: Row, repo_order: dict[str, int]) -> tuple[int, int, int]:
    level_rank = LEVELS.index(row.level) if row.level in LEVELS else len(LEVELS)
    return level_rank, repo_order.get(row.issue.repo, len(repo_order)), row.issue.number


def compute_blocks(rows: list[Row]) -> dict[str, tuple[str, ...]]:
    """Invert every ``blocked_by`` (waits.yaml and GitHub) into ``blocks``."""
    blocks: dict[str, list[str]] = defaultdict(list)
    for row in rows:
        for target in row.blocked_by:
            if row.key not in blocks[target]:
                blocks[target].append(row.key)
    return {target: tuple(keys) for target, keys in blocks.items()}


def build_rows(snap: Snapshot, entries: dict[str, Entry]) -> list[Row]:
    """Join open issues with their entries, sorted by level, repository, number."""
    repo_order = {repo.name: i for i, repo in enumerate(snap.repos)}
    rows = []
    for key, issue in snap.issues.items():
        entry = entries.get(key)
        if entry is None:
            continue
        merged = tuple(dict.fromkeys(entry.blocked_by + issue.api_blocked_by))
        rows.append(Row(issue=issue, entry=entry, blocked_by=merged))
    rows.sort(key=lambda r: _sort_key(r, repo_order))
    blocks = compute_blocks(rows)
    for row in rows:
        row.blocks = blocks.get(row.key, ())
    return rows


def newest_movement(snap: Snapshot) -> datetime | None:
    """Return the newest movement over all open issues (the 'issue state')."""
    stamps = [issue.last_movement for issue in snap.issues.values()]
    return max(stamps) if stamps else None


def stale_rows(rows: list[Row], as_of: datetime | None) -> list[Row]:
    """Rows that wait for nothing and have not moved for more than 14 days.

    Measured against the issue state, not the wall clock, so the same data
    always renders the same file.
    """
    if as_of is None:
        return []
    return [
        r
        for r in rows
        if r.entry.waits == "nothing" and r.issue.last_movement < as_of - STALE_AFTER
    ]


# --- rendering -----------------------------------------------------------------

TABLE_HEAD = (
    "| Repo | # | Title | Level | Waits for | Blocks | Last movement |\n"
    "|---|---|---|---|---|---|---|"
)


def _waits_cell(row: Row) -> str:
    if row.blocked_by:
        return "issue: " + ", ".join(row.blocked_by)
    return row.entry.waits


def _table(rows: list[Row], *, since: bool = False) -> str:
    if not rows:
        return "None."
    lines = [TABLE_HEAD]
    for row in rows:
        moved = row.issue.last_movement.strftime("%Y-%m-%d")
        lines.append(
            f"| {row.issue.repo} | [#{row.issue.number}]({row.issue.url}) | {_clean(row.entry.summary)} "
            f"| {row.level} | {_clean(_waits_cell(row))} | {', '.join(row.blocks) or '-'} "
            f"| {'since ' + moved if since else moved} |"
        )
    return "\n".join(lines)


def _state_line(snap: Snapshot) -> str:
    newest = newest_movement(snap)
    return f"Issue state as of {_fmt_ts(newest) if newest else 'no open issue'} UTC"


BOARD_RULES = """\
- Generated by `make status` (`scripts/status_board.py`); never edit it by hand. A row
  changes by editing `status/waits.yaml` or the issue on GitHub and running `make status`.
- Title is the entry's `summary`; Level is the issue's `P0`..`P5` label (`none` without one).
- Waits for is the entry's `waits`: `decision` (an answer from the owner), `external`
  (a device, a key, an upstream release, a waiting period), `issue` (the issues named in
  `blocked_by` or in GitHub's own blocked-by relation), `nothing`.
- Blocks is computed as the inverse of every `blocked_by`, never written by hand.
- Last movement is the newest comment, commit or pull request that works on the issue,
  from its timeline, not its `updated_at` (a label change is not movement). A PR works on
  an issue when a closing keyword (`Closes`, `Fixes`, `Resolves`) or `Refs` in its title
  or body names it, a commit when its message does; a mention in the prose of a PR or a
  commit, or in another issue, is not movement.
  PRs labelled `status-board` and the nightly report issue never count.
- In progress lists open issues that an open pull request works on; they leave Doable now.
- Stale lists issues that wait for nothing and have not moved for more than 14 days before
  the issue state above; they also stay in their own block, so a decision is made on them.
- Sorting is level, then the repository order of `status/repos.yaml`, then number. It is not
  a recommended order; the order is the owner's, in `status/plan.md`.
- `make status-check` (nightly in `.github/workflows/status-board.yml`) fails when an open
  issue has no entry, an entry belongs to a closed or unknown issue, an issue moved after
  its `checked` date, a `blocked_by` names a closed or unknown issue, this file is older
  than the newest issue movement or differs from a fresh run, or an ecosystem repository
  is missing from `status/repos.yaml`."""


def render_board(snap: Snapshot, rows: list[Row]) -> str:
    """Render BOARD.md."""
    in_progress = [r for r in rows if r.issue.open_pr_refs]
    doable = [r for r in rows if r.entry.waits == "nothing" and not r.issue.open_pr_refs]
    decision = [r for r in rows if r.entry.waits == "decision"]
    waiting = [r for r in rows if r.entry.waits in ("external", "issue")]
    stale = stale_rows(rows, newest_movement(snap))
    warn = ""
    if len(in_progress) > MAX_IN_PROGRESS:
        warn = (
            f"\n\n> Warning: more than {MAX_IN_PROGRESS} issues in progress "
            f"({len(in_progress)}); the board's rule is at most {MAX_IN_PROGRESS} at a time."
        )
    head = (
        "# BOARD\n\n"
        f"> Generated by `make status` at {_fmt_ts(snap.generated_at)} UTC.\n"
        f"> {_state_line(snap)} (newest comment, commit or working pull request on an open issue).\n"
        "> Do not edit by hand. Sources: `status/waits.yaml`, `status/repos.yaml` and the GitHub API."
    )
    sections = [
        head,
        f"## In progress\n\nOpen issues an open pull request works on (Closes, Fixes, Resolves or Refs).{warn}\n\n{_table(in_progress)}",
        f"## Doable now\n\nWaits for nothing.\n\n{_table(doable)}",
        "## Waiting only for a decision\n\nThe cheapest progress: each needs an answer, not work.\n\n"
        f"{_table(decision)}",
        f"## Waiting (external / other issue)\n\n{_table(waiting)}",
        "## Stale\n\nWaits for nothing and no movement for more than 14 days.\n\n"
        f"{_table(stale, since=True)}",
        f"## Rules\n\n{BOARD_RULES}",
    ]
    return _sanitize("\n\n---\n\n".join(sections) + "\n")


STATUS_RULES = """\
- Generated by `make status` (`scripts/status_board.py`); never edit it by hand.
- Now: the newest release of each repository that has releases, and the open pull requests
  over all repositories (regeneration pull requests labelled `status-board` excluded).
- Waiting for you: every entry of `status/waits.yaml` with `waits: decision`; the ID is the
  stable `repo#N`, Needed by is the optional `needed_by`.
- Plan: `status/plan.md`, written by the owner; the generator only copies it.
- Recently happened: the five newest merged pull requests and closed issues over all
  repositories.
- Where things are: `status/repos.yaml`.
- `make status-check` fails when this file is older than the newest issue movement or
  differs from a fresh run; see BOARD.md for the full list."""


def render_status(snap: Snapshot, rows: list[Row], plan: str | None) -> str:
    """Render STATUS.md."""
    if len(snap.now_lines) > MAX_NOW_LINES:
        raise ValueError(
            f"Now has {len(snap.now_lines)} lines, at most {MAX_NOW_LINES} are allowed"
        )
    decisions = [r for r in rows if r.entry.waits == "decision"]
    if decisions:
        waiting = ["| ID | What | Needed by | Where |", "|---|---|---|---|"]
        waiting += [
            f"| {r.key} | {_clean(r.entry.detail)} | {_clean(r.entry.needed_by or '-')} "
            f"| [evidence]({r.entry.evidence}) |"
            for r in decisions
        ]
        waiting_text = "\n".join(waiting)
    else:
        waiting_text = "Nothing waits for a decision."
    plan_text = plan.strip() if plan and plan.strip() else "No plan recorded yet."
    recent_text = "\n".join(f"- {_clean(line)}" for line in snap.recent) or "Nothing recorded."
    where = ["| Repository | What it holds | Releases |", "|---|---|---|"]
    for repo in snap.repos:
        release = {"github": "GitHub Releases", "tag": "tags", "none": "-"}[repo.release]
        if repo.npm:
            release += f", npm `{repo.npm}`"
        where.append(
            f"| [{repo.name}](https://github.com/{snap.owner}/{repo.name}) "
            f"| {_clean(repo.role)} | {release} |"
        )
    now_text = "\n".join(f"- {_clean(line)}" for line in snap.now_lines) or "Nothing recorded."
    text = (
        "# STATUS: Adaptive Learner ecosystem\n\n"
        f"Generated by `make status` at {_fmt_ts(snap.generated_at)} UTC.\n"
        f"{_state_line(snap)}. Do not edit by hand; sources: `status/waits.yaml`, "
        "`status/repos.yaml`, `status/plan.md` and the GitHub API.\n\n"
        f"## 1. Now\n\n{now_text}\n\n"
        f"## 2. Waiting for you\n\n{waiting_text}\n\n"
        f"## 3. Plan\n\n{plan_text}\n\n"
        f"## 4. Recently happened\n\n{recent_text}\n\n"
        "## 5. Where things are\n\n" + "\n".join(where) + "\n\n"
        f"## Rules for this file\n\n{STATUS_RULES}\n"
    )
    return _sanitize(text)


def _sanitize(text: str) -> str:
    text = text.replace("—", "-").replace("–", "-")
    return "\n".join(line.rstrip() for line in text.split("\n"))


def normalize_for_compare(text: str) -> str:
    """Drop the generated-at line; everything else must match a fresh render."""
    return "\n".join(line for line in text.split("\n") if not GENERATED_RE.match(line))


# --- the check ------------------------------------------------------------------


def _target_state(target: str, snap: Snapshot) -> str | None:
    if target in snap.issues:
        return None
    return "closed" if target in snap.closed_keys else "unknown"


def _file_findings(name: str, text: str, fresh: str, newest: datetime | None) -> list[str]:
    if not text.strip():
        return [f"{name}: missing; run make status"]
    findings = []
    match = STATE_RE.search(text)
    stated = (
        datetime.strptime(match.group(1), "%Y-%m-%d %H:%M").replace(tzinfo=UTC) if match else None
    )
    if newest is not None and (stated is None or stated < newest.replace(second=0, microsecond=0)):
        findings.append(
            f"{name}: older than the newest issue movement ({_fmt_ts(newest)} UTC); run make status"
        )
    if normalize_for_compare(text) != normalize_for_compare(fresh):
        findings.append(f"{name}: differs from a fresh run; run make status")
    return findings


def check(
    snap: Snapshot, entries: dict[str, Entry], board: str, status: str, plan: str | None
) -> list[str]:
    """Return every finding; an empty list means the files and waits.yaml hold."""
    findings: list[str] = []
    for key in snap.issues:
        if key not in entries:
            findings.append(f"{key}: open issue has no entry in status/waits.yaml")
    for key, entry in entries.items():
        issue = snap.issues.get(key)
        if issue is None:
            state = _target_state(key, snap)
            findings.append(f"{key}: status/waits.yaml has an entry for a {state} issue; remove it")
            continue
        moved = issue.last_movement.date()
        if moved > entry.checked:
            findings.append(
                f"{key}: moved on {moved} after its classification was checked on "
                f"{entry.checked}; check the classification again"
            )
        for target in entry.blocked_by + issue.api_blocked_by:
            state = _target_state(target, snap)
            if state:
                findings.append(f"{key}: blocked_by names {target}, a {state} issue")
        if issue.api_blocked_by and entry.waits != "issue":
            findings.append(
                f"{key}: GitHub says blocked by {', '.join(issue.api_blocked_by)}, "
                f"but status/waits.yaml says waits {entry.waits}"
            )
    listed = {repo.name for repo in snap.repos}
    for repo in snap.ecosystem_repos:
        if repo not in listed:
            findings.append(f"{repo}: ecosystem repository is not listed in status/repos.yaml")
    rows = build_rows(snap, entries)
    newest = newest_movement(snap)
    findings += _file_findings("BOARD.md", board, render_board(snap, rows), newest)
    findings += _file_findings("STATUS.md", status, render_status(snap, rows, plan), newest)
    return findings


